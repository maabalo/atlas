"""
Atlas — atlas_export.py: write the graph out.

  graph.json       the full graph (nodes + edges) for other tools
  GRAPH_REPORT.md  a readable summary: counts, files, hubs, health checks
  graph.html       one self-contained interactive page (opens from file://,
                   no server needed): viewer/index.html with style.css,
                   app.js and the graph data inlined

TABLE OF CONTENTS
  01  JSON
  02  Markdown report
  03  Interactive HTML page
  04  Writing all three
"""

from __future__ import annotations

import base64
import hashlib
import json
import re
from collections import Counter
from dataclasses import asdict
from datetime import date
from pathlib import Path

import atlas_graph as ag

VIEWER_DIR = Path(__file__).resolve().parent / "viewer"
TYPE_LABELS = {
    "folder": "Folders", "file": "Files", "function": "Functions",
    "class": "Classes", "html-id": "HTML ids", "css-class": "CSS classes",
}  # fmt: skip


# =============================================================================
# 01  JSON
# =============================================================================
def graph_to_dict(graph: ag.Graph) -> dict:
    """The graph as plain data (stable order, so the file diffs cleanly). Each node carries its
    community number (-1 when it's in none), and meta lists the communities."""
    groups = ag.communities(graph)
    group_of = {member: c.id for c in groups for member in c.members}
    ordered = sorted(graph.nodes.values(), key=lambda n: n.id)
    nodes = [{**asdict(n), "community": group_of.get(n.id, -1)} for n in ordered]
    edges = [asdict(e) for e in sorted(graph.edges.values(), key=lambda e: (e.source, e.kind, e.target))]
    checks = {name: [n.id for n in found] for name, found in ag.health(graph).items()}
    meta = {"project": Path(graph.root).name, "generated": date.today().isoformat(), "tool": "Atlas"}
    meta["counts"] = dict(Counter(n["type"] for n in nodes))
    meta["communities"] = [{"id": c.id, "name": c.name, "size": len(c.members), "hub": c.hub} for c in groups]
    if graph.projects:
        meta["projects"] = graph.projects  # a combined map: the viewer shows which project a file is in
    if graph.satellite:
        meta["satellite"] = graph.satellite  # this project is drawn as Claude's core, inside the globe
    if graph.touches:
        meta["claude_touches"] = dict(
            sorted(graph.touches.items())
        )  # files Claude edited or created: rays from the core
    return {"meta": meta, "nodes": nodes, "edges": edges, "health": checks, "errors": graph.errors}


# =============================================================================
# 02  MARKDOWN REPORT
# =============================================================================
def report_markdown(graph: ag.Graph) -> str:
    """GRAPH_REPORT.md: an overview a person can read in a minute."""
    parts = [f"# Code map: {Path(graph.root).name}", "", f"_Generated by Atlas on {date.today().isoformat()}._", ""]
    parts += report_counts(graph) + report_files(graph) + report_hubs(graph) + report_communities(graph)
    parts += report_health(graph)
    if graph.errors:
        parts += ["## Files Atlas couldn't read", ""] + [f"- {e}" for e in graph.errors] + [""]
    parts += [
        "---",
        "Links marked **inferred** were matched by name (not written explicitly in the code).",
        "Health checks list *possible* problems: code that builds names at runtime can use things",
        "Atlas can't see, so check before deleting anything.",
    ]
    return "\n".join(parts) + "\n"


def report_counts(graph: ag.Graph) -> list[str]:
    """A table of how many of each kind of thing the project has."""
    counts = Counter(n.type for n in graph.nodes.values())
    rows = [f"| {TYPE_LABELS[t]} | {counts[t]} |" for t in TYPE_LABELS if counts[t]]
    links = Counter(e.kind for e in graph.edges.values())
    link_text = ", ".join(f"{k} {v}" for k, v in sorted(links.items()))
    return ["## Overview", "", "| Kind | Count |", "|---|---|", *rows, "", f"Links: {link_text}.", ""]


def report_files(graph: ag.Graph) -> list[str]:
    """Each file with its language and how many functions/classes it defines."""
    defined = Counter(n.file for n in graph.nodes.values() if n.type in ("function", "class"))
    files = sorted((n for n in graph.nodes.values() if n.type == "file"), key=lambda n: n.name)
    rows = [f"| `{f.name}` | {f.lang} | {defined[f.name] or '—'} |" for f in files]
    return ["## Files", "", "| File | Language | Functions/classes |", "|---|---|---|", *rows, ""]


def report_hubs(graph: ag.Graph) -> list[str]:
    """The most-connected functions: the riskiest to change."""
    found = ag.hubs(graph, 10)
    if not found:
        return []
    rows = [f"| `{n.name}` | `{n.file}:{n.line}` | {d} |" for n, d in found]
    intro = "Most-connected functions and classes. Changes here affect the most code, so test them well."
    return ["## Hubs", "", intro, "", "| Name | Defined at | Links |", "|---|---|---|", *rows, ""]


def report_communities(graph: ag.Graph) -> list[str]:
    """The subsystems, biggest first (the 15 biggest)."""
    found = ag.communities(graph)
    if not found:
        return []
    rows = [f"| {c.id} | {c.name} | {len(c.members)} | `{c.file}` |" for c in found[:15]]
    intro = "Groups of code linked mostly to each other (Louvain method). Each is named after its main file and hubs."
    return ["## Communities", "", intro, "", "| # | Name | Members | Main file |", "|---|---|---|---|", *rows, ""]


def report_health(graph: ag.Graph) -> list[str]:
    """The three health checks, each as a list with file:line."""
    titles = {
        "unused_functions": "Functions nothing calls or uses",
        "unused_css_classes": "CSS classes not used in any HTML or JavaScript",
        "missing_ids": "Ids used by code or markup but not declared in any HTML",
    }
    parts = ["## Health checks", ""]
    for key, found in ag.health(graph).items():
        parts.append(f"### {titles[key]} ({len(found)})")
        parts += [f"- `{n.name}`: `{n.file}:{n.line}`" for n in sorted(found, key=lambda n: (n.file, n.line))]
        parts += ["- None found ✓" if not found else "", ""]
    return parts


# =============================================================================
# 03  INTERACTIVE HTML PAGE
# =============================================================================
def html_page(graph: ag.Graph) -> str:
    """viewer/index.html with its CSS, JS and the graph data inlined into one file."""
    template = (VIEWER_DIR / "index.html").read_text(encoding="utf-8")
    css = (VIEWER_DIR / "style.css").read_text(encoding="utf-8")
    core = (VIEWER_DIR / "core.js").read_text(encoding="utf-8")
    js = (VIEWER_DIR / "app.js").read_text(encoding="utf-8")
    data = safe_script_json(graph_to_dict(graph))
    replacements = {
        '<link rel="stylesheet" href="style.css" />': f"<style>\n{css}</style>",
        '<script id="graphData" type="application/json">{}</script>': (
            f'<script id="graphData" type="application/json">{data}</script>'
        ),
        '<script src="core.js"></script>': f"<script>\n{core}</script>",
        '<script src="app.js"></script>': f"<script>\n{js}</script>",
    }
    for placeholder, content in replacements.items():
        if placeholder not in template:
            raise ValueError(f"viewer/index.html is missing the placeholder: {placeholder}")
        template = template.replace(placeholder, content)
    return with_content_policy(template)


# The page may only run its own inline scripts and styles (by hash), load Google Fonts, and use data: images.
# Nothing else: no other scripts, no network requests, no forms, no frames.
CSP_TEMPLATE = (
    "default-src 'none'; script-src {scripts}; style-src {styles} https://fonts.googleapis.com; "
    "font-src https://fonts.gstatic.com; img-src data:; base-uri 'none'; form-action 'none'"
)


def with_content_policy(page: str) -> str:
    """Add a Content-Security-Policy that allows exactly this page's inline scripts and styles (by their
    SHA-256 hashes), so nothing injected into a map could run. The JSON data block isn't a script and needs none."""

    def hashes(pattern: str) -> str:
        found = re.findall(pattern, page, flags=re.S)
        return " ".join(
            f"'sha256-{base64.b64encode(hashlib.sha256(body.encode()).digest()).decode()}'" for body in found
        )

    scripts = hashes(r"<script>(.*?)</script>")
    styles = hashes(r"<style>(.*?)</style>")
    meta = (
        f'<meta http-equiv="Content-Security-Policy" content="{CSP_TEMPLATE.format(scripts=scripts, styles=styles)}" />'
    )
    return page.replace('<meta charset="utf-8" />', f'<meta charset="utf-8" />\n    {meta}', 1)


def safe_script_json(data: dict) -> str:
    """JSON that can't end its <script> early: every "<" becomes \\u003c (still valid JSON)."""
    return json.dumps(data, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")


# =============================================================================
# 04  WRITING ALL THREE
# =============================================================================
def write_outputs(graph: ag.Graph, out_dir: Path) -> dict[str, Path]:
    """Write graph.json, GRAPH_REPORT.md and graph.html into out_dir; return their paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    files = {
        "json": (out_dir / "graph.json", json.dumps(graph_to_dict(graph), indent=1, ensure_ascii=False)),
        "report": (out_dir / "GRAPH_REPORT.md", report_markdown(graph)),
        "html": (out_dir / "graph.html", html_page(graph)),
    }
    for path, content in files.values():
        path.write_text(content, encoding="utf-8")
    return {key: path for key, (path, _content) in files.items()}
